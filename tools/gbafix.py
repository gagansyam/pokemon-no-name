def patch_gba(filename, title="POKEREALTIME", game_code="BPRE"):
    with open(filename, "rb") as f:
        data = bytearray(f.read())

    # Pad to minimum 512 bytes if too small
    if len(data) < 512:
        data.extend(b'\x00' * (512 - len(data)))

    # 1. Nintendo Logo at 0x04 - 0x9F
    data[0x04:0x04 + len(NINTENDO_LOGO)] = NINTENDO_LOGO

    # 2. Game Title (12 chars, uppercase ASCII, zero-padded) at 0xA0 - 0xAB
    title_bytes = title.encode('ascii')[:12].ljust(12, b'\x00')
    data[0xA0:0xAC] = title_bytes

    # 3. Game Code (4 chars) at 0xAC - 0xAF
    code_bytes = game_code.encode('ascii')[:4].ljust(4, b'\x00')
    data[0xAC:0xB0] = code_bytes

    # 4. Maker Code (0x01 = Nintendo) at 0xB0 - 0xB1
    data[0xB0:0xB2] = b'01'

    # 5. Fixed value 0x96 at 0xB2
    data[0xB2] = 0x96

    # 6. Main unit code at 0xB3 (0x00)
    data[0xB3] = 0x00

    # 7. Device type at 0xB4 (0x00)
    data[0xB4] = 0x00

    # 8. Reserved at 0xB5 - 0xBB (7 zeroes)
    data[0xB5:0xBC] = b'\x00' * 7

    # 9. Software version at 0xBC (0x00)
    data[0xBC] = 0x00

    # 10. Complement check at 0xBD
    chk = 0
    for i in range(0xA0, 0xBD):
        chk = (chk - data[i]) & 0xFF
    chk = (chk - 0x19) & 0xFF
    data[0xBD] = chk

    with open(filename, "wb") as f:
        f.write(data)

    print(f"[gbafix] Patched '{filename}': Title='{title}', Code='{game_code}', Checksum=0x{chk:02X}, Size={len(data)} bytes")

