def analyze_sheet(filepath: str, frame_w: int, frame_h: int, name: str):
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"Sprite sheet not found: {filepath}")

    img = Image.open(path).convert("RGBA")
    w, h = img.size

    # Validate grid alignment
    if w % frame_w != 0:
        raise ValueError(f"[{name}] Width {w} is not divisible by frame_w {frame_w}")
    if h % frame_h != 0:
        raise ValueError(f"[{name}] Height {h} is not divisible by frame_h {frame_h}")

    cols = w // frame_w
    rows = h // frame_h

    if rows != 8:
        print(f"Warning: [{name}] Expected 8 directional rows (PMD format), found {rows} rows.", file=sys.stderr)

    # Transparency audit
    alpha_channel = img.getchannel('A')
    min_alpha, max_alpha = alpha_channel.getextrema()
    if min_alpha == 255:
        print(f"Warning: [{name}] Sheet has NO transparent pixels! Ensure background is keyed to alpha=0.", file=sys.stderr)

    # Frame 0 neutral inspection (Direction 0: South / Down)
    neutral_crop = img.crop((0, 0, frame_w, frame_h))
    neutral_bbox = neutral_crop.getbbox()
    if not neutral_bbox:
        neutral_bbox = (0, 0, frame_w, frame_h)

    foot_y = neutral_bbox[3]
    body_center_x = (neutral_bbox[0] + neutral_bbox[2]) // 2
    body_center_y = (neutral_bbox[1] + neutral_bbox[3]) // 2

    # Anchor X defaults to frame_w // 2 for symmetry
    anchor_x = frame_w // 2
    # Anchor Y represents character body center
    anchor_y = body_center_y

    print(f"[{name}] {w}x{h} -> {cols} frames, {rows} dirs | Frame: {frame_w}x{frame_h} | Center Anchor: ({anchor_x}, {anchor_y}) | Foot Y: {foot_y}")

    return {
        "name": name,
        "file": str(path),
        "frame_w": frame_w,
        "frame_h": frame_h,
        "num_frames": cols,
        "num_dirs": rows,
        "anchor_x": anchor_x,
        "anchor_y": anchor_y,
        "foot_y": foot_y
    }

def generate_header(manifests, output_path: str):
    header_content = [
        "#pragma once",
        "",
        "// Auto-generated by tools/process_sprite_sheet.py",
        "// Do not edit manually.",
        "",
        "struct AnimationMeta {",
        "    const char* filepath;",
        "    int frame_w;",
        "    int frame_h;",
        "    int num_frames;",
        "    int num_dirs;",
        "    int anchor_x;",
        "    int anchor_y;",
        "    int foot_y;",
        "};",
        ""
    ]

    for m in manifests:
        var_name = f"META_{m['name'].upper()}"
        rel_file = m['file'].replace('\\', '/')
        if "assets/" in rel_file:
            rel_file = rel_file[rel_file.index("assets/"):]

        header_content.append(f"inline constexpr AnimationMeta {var_name} = {{")
        header_content.append(f"    \"{rel_file}\",")
        header_content.append(f"    {m['frame_w']}, {m['frame_h']},")
        header_content.append(f"    {m['num_frames']}, {m['num_dirs']},")
        header_content.append(f"    {m['anchor_x']}, {m['anchor_y']}, {m['foot_y']}")
        header_content.append("};\n")

    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w") as f:
        f.write("\n".join(header_content) + "\n")

    print(f"Manifest successfully written to: {out_file}")

def main():
    parser = argparse.ArgumentParser(description="Sprite sheet validator and C++ manifest generator.")
    parser.add_argument("--batch", metavar="DIR", help="Batch process known sheets in directory")
    parser.add_argument("--output", "-o", default="src/sprite_manifest.hpp", help="Output C++ header path")
    parser.add_argument("sheet", nargs="?", help="Sprite sheet PNG path")
    parser.add_argument("frame_w", nargs="?", type=int, help="Frame width in pixels")
    parser.add_argument("frame_h", nargs="?", type=int, help="Frame height in pixels")
    parser.add_argument("name", nargs="?", help="Animation identifier name")

    args = parser.parse_args()

    manifests = []

    if args.batch:
        base_dir = Path(args.batch)
        for cfg in KNOWN_SHEETS:
            sheet_file = base_dir / cfg["file"]
            if sheet_file.exists():
                manifests.append(analyze_sheet(str(sheet_file), cfg["frame_w"], cfg["frame_h"], cfg["name"]))
            else:
                print(f"Warning: Sheet {sheet_file} not found during batch scan.", file=sys.stderr)
        generate_header(manifests, args.output)
    elif args.sheet and args.frame_w and args.frame_h and args.name:
        meta = analyze_sheet(args.sheet, args.frame_w, args.frame_h, args.name)
        manifests.append(meta)
        if args.output:
            generate_header(manifests, args.output)
    else:
        parser.print_help()
        sys.exit(1)

if __name__ == "__main__":
    main()
